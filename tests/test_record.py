"""Unit tests for the derived views every extractor shares."""
from __future__ import annotations

import pytest

from llmstxt_analysis.record import BOM, Record, registered_domain, safe_host


def mk(content: str, url: str = "https://example.com/llms.txt") -> Record:
    return Record(0, 0, 0, 0, url, content, "{}", "", "", "text/plain")


@pytest.mark.parametrize(
    "host,expected",
    [
        ("example.com", "example.com"),
        ("www.example.com", "example.com"),
        ("a.b.example.com", "example.com"),
        ("shop.example.co.uk", "example.co.uk"),
        ("www.example.com.au", "example.com.au"),
        ("example.com.br", "example.com.br"),
        ("localhost", "localhost"),
        ("", ""),
    ],
)
def test_registered_domain(host, expected):
    assert registered_domain(host) == expected


@pytest.mark.parametrize(
    "url",
    [
        "https://[not-an-ipv6]/page",          # ValueError: Invalid IPv6 URL
        "https://[::1/page",
        "http://exa mple.com/x",
        "https://",
        "",
        "not a url at all",
    ],
)
def test_unparseable_urls_never_raise(url):
    """One malformed link target used to kill an entire extraction worker."""
    assert isinstance(safe_host(url), str)
    rec = mk(f"# T\n- [x]({url})\n", url=url)
    assert isinstance(rec.host, str)
    assert isinstance(rec.regdomain, str)


def test_bom_is_stripped_from_body_but_recorded():
    r = mk(BOM + "# Title\n")
    assert r.content.startswith(BOM)
    assert r.body.startswith("# Title")
    assert r.first_line == "# Title"


def test_links_parsing():
    r = mk(
        "# T\n"
        "- [Home](https://example.com/): the home page\n"
        "- [Rel](/about)\n"
        "- [Angle](<https://example.com/a b>)\n"
        "- [Mail](mailto:a@b.com)\n"
    )
    targets = [t for _, t in r.links]
    assert "https://example.com/" in targets
    assert "/about" in targets
    assert "https://example.com/a b" in targets, "angle-bracket targets are unwrapped"
    assert "mailto:a@b.com" in targets


def test_prose_drops_link_bullets_and_urls():
    r = mk(
        "# Acme Corporation\n"
        "> We build things for people who build things.\n"
        "- [Products](https://example.com/products): our catalogue\n"
        "- [About](https://example.com/about)\n"
    )
    assert "Acme Corporation" in r.prose
    assert "build things" in r.prose
    assert "https://" not in r.prose
    assert "catalogue" not in r.prose, "link bullets are excluded entirely"


TEMPLATE = (
    "# {name}\n"
    "> {summary}\n"
    "\n"
    "## Agent access\n"
    "This site is powered by Widget and exposes a machine endpoint for agents.\n"
    "Generated by Widget SEO v{ver}, this is an llms.txt file.\n"
    "\n"
    "## Pages\n"
    "- [Home]({url})\n"
    "Contact {email}\n"
)


def test_skeleton_ignores_the_site_specific_parts():
    """Two sites running the same generator must share one skeleton."""
    a = mk(TEMPLATE.format(name="Alpha Ltd", summary="We sell widgets.", ver="1.2.3",
                           url="https://alpha.com/", email="a@alpha.com"))
    b = mk(TEMPLATE.format(name="Beta GmbH", summary="Wir verkaufen Dinge.", ver="1.9.0",
                           url="https://beta.de/impressum", email="b@beta.de"))
    assert a.skeleton == b.skeleton


def test_skeleton_is_script_independent():
    """Placeholders collapse identically for space-separated and unspaced scripts.

    This makes the signature independent of *script*, not of *language*: a
    template whose Latin boilerplate is also translated still yields one
    cluster per language. See test_integration for the real-data behaviour.
    """
    a = mk(TEMPLATE.format(name="X", summary="s", ver="1", url="https://x.com/", email="x@x.com")
           .replace("This site is powered by Widget and exposes a machine endpoint for agents.",
                    "このサイトは Widget で作成されており、エージェント用のエンドポイントがあります。"))
    b = mk(TEMPLATE.format(name="Y", summary="t", ver="2", url="https://y.com/", email="y@y.com")
           .replace("This site is powered by Widget and exposes a machine endpoint for agents.",
                    "Цей сайт на базі Widget підтримує кінцеву точку для агентів."))
    assert a.skeleton == b.skeleton


def test_skeleton_distinguishes_different_templates():
    a = mk(TEMPLATE.format(name="A", summary="s", ver="1", url="https://a.com/", email="a@a.com"))
    b = mk("# B\n> s\n\n## Sitemaps\n- [XML Sitemap](https://b.com/sitemap.xml)\n"
           "Generated by Other SEO v2, this is an llms.txt file.\n")
    assert a.skeleton != b.skeleton


def test_skeleton_falls_back_for_link_only_documents():
    """A document that is nothing but a title and bullets must not collapse to ''."""
    a = mk("# Alpha\n- [One](https://alpha.com/1)\n- [Two](https://alpha.com/2)\n")
    b = mk("# Beta\n- [Three](https://beta.com/3)\n- [Four](https://beta.com/4)\n")
    assert a.skeleton
    assert a.skeleton != b.skeleton


def test_scan_window_is_bounded_but_keeps_the_tail():
    body = "HEADMARKER\n" + ("x" * 60_000) + "\nTAILMARKER"
    r = mk(body)
    assert len(r.scan) < len(body)
    assert "HEADMARKER" in r.scan
    assert "TAILMARKER" in r.scan


def test_is_full_and_url_views():
    assert mk("", "https://a.example.org/llms-full.txt").is_full
    assert not mk("", "https://a.example.org/llms.txt").is_full
    r = mk("", "https://Sub.Example.CO.UK/llms.txt")
    assert r.host == "sub.example.co.uk"
    assert r.regdomain == "example.co.uk"
    assert r.tld == "uk"


def test_headers_parse_defensively():
    assert mk("", ).headers == {}
    r = Record(0, 0, 0, 0, "u", "", '{"Server": "nginx", "Content-Type": "text/plain"}', "", "", "")
    assert r.headers["server"] == "nginx"
    bad = Record(0, 0, 0, 0, "u", "", "not json", "", "", "")
    assert bad.headers == {}


def test_real_records_have_consistent_views(records):
    """Derived views must never contradict the raw content (real corpus data)."""
    for r in records:
        assert len(r.body) <= len(r.content)
        assert len(r.skeleton) <= 4000
        assert len(r.prose) <= 4200
        assert r.first_line in ("", *(l.strip() for l in r.lines))
        if r.host:
            assert r.regdomain.endswith(r.tld) or not r.tld
