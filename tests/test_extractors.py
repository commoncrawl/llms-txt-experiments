CONF = ConformanceExtractor()
GEN = GeneratorExtractor()
POL = PolicyExtractor()
ABU = AbuseExtractor()
AGT = AgentAccessExtractor()
CORE = CoreExtractor()

SPEC_DOC = """# Acme Docs

> Everything an agent needs to answer questions about Acme.

Acme builds inventory software for small warehouses. The links below cover the
product, the API and the support material.

## Docs

- [Getting started](https://acme.example/start): install and first run
- [API reference](https://acme.example/api): every endpoint

## Optional

- [Changelog](https://acme.example/changelog)
"""


def mk(content: str, url: str = "https://acme.example/llms.txt") -> Record:
    return Record(0, 0, 0, 0, url, content, "{}", "2026-07-10T00:00:00Z", "", "text/plain")


# --------------------------------------------------------------------------
# A — conformance
# --------------------------------------------------------------------------
def test_fully_conformant_document():
    f = CONF.extract(mk(SPEC_DOC))
    assert f["doc_kind"] == "markdown"
    assert f["conformance_level"] == 4
    assert f["starts_with_h1"] and f["n_h1"] == 1
    assert f["blockquote_follows_h1"] and f["has_prose_body"]
    assert f["has_optional_section"]
    assert f["n_links"] == 3 and f["n_link_bullets"] == 3
    assert f["n_links_with_notes"] == 2
    assert f["n_offsite_links"] == 0 and f["offsite_ratio"] == 0


@pytest.mark.parametrize(
    "content,level",
    [
        ("{\"error\": 1}", 0),
        ("just some prose without any markdown at all, at length", 0),
        ("- [a](https://x.example/)\n- [b](https://x.example/b)\n", 1),
        ("# Title\n\n## Pages\n- [a](https://acme.example/a)\n", 2),
        ("# Title\n> Summary here\n\nSome body prose that is long enough to count.\n", 3),
        (SPEC_DOC, 4),
    ],
)
def test_conformance_ladder(content, level):
    assert CONF.extract(mk(content))["conformance_level"] == level
    assert level in CONFORMANCE_LABELS


@pytest.mark.parametrize(
    "content,kind",
    [
        ("", "empty"),
        ("   \n\n ", "empty"),
        ('{"result": 110, "msg": "maintenance"}', "json"),
        ("[1,2,3]", "json"),
        ("<!doctype html><html><body>404</body></html>", "html"),
        ("User-agent: *\nDisallow: /\nSitemap: /sitemap.xml\n", "robots_txt"),
        ("---\ntitle: X\nurl: https://x.example\n---\n\n# X\n", "yaml_frontmatter"),
        ("spec: llmstxt/1.0\nsite: https://x.example\nowner: X\ncontact: a@x.example\n", "yaml"),
        ("# Title\n- [a](https://x.example/)\n", "markdown"),
    ],
)
def test_doc_kind(content, kind):
    assert CONF.extract(mk(content))["doc_kind"] == kind


def test_offsite_and_relative_links_are_counted():
    f = CONF.extract(mk(
        "# T\n"
        "- [own](https://acme.example/a)\n"
        "- [www is the same site](https://www.acme.example/b)\n"
        "- [other](https://spam.example/c)\n"
        "- [other2](https://ads.example/d)\n"
        "- [relative](/about)\n"
        "- [mail](mailto:x@acme.example)\n"
    ))
    assert f["n_relative_links"] == 1
    assert f["n_offsite_links"] == 2
    assert f["n_offsite_domains"] == 2
    assert f["n_links"] == 6
    assert "relative_links" in f["conf_flags"]


def test_bom_is_flagged_not_fatal():
    f = CONF.extract(mk("﻿# Title\n> Summary\n\n## S\n- [a](https://acme.example/a): n\n"))
    assert f["has_bom"] and "bom" in f["conf_flags"]
    assert f["starts_with_h1"]
    assert f["conformance_level"] == 4


