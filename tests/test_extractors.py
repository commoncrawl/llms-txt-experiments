def test_language_batch_and_fallback_paths():
    ex = LanguageExtractor()
    ex.setup()
    recs = [
        mk("# Acme\n> The quick brown fox jumps over the lazy dog, repeatedly and at length.\n"),
        mk("# Acme\n> Der schnelle braune Fuchs springt immer wieder über den faulen Hund.\n"),
        mk("# Acme\n> 素早い茶色の狐が怠け者の犬を何度も飛び越えるのを見ました。\n"),
        mk(""),
    ]
    out = ex.extract_batch(recs)
    assert out[0]["lang"] == "eng" and out[0]["lang_source"] == "cld2"
    assert out[1]["lang"] == "deu"
    assert out[2]["lang"] == "jpn"
    assert out[3]["lang"] == "und" and out[3]["lang_source"] == "none"


def test_token_counts_are_exact_and_scale():
    ex = TokenExtractor()
    ex.setup()
    out = ex.extract_batch([mk(""), mk("hello world"), mk("hello world " * 1000)])
    assert out[0]["n_tokens"] == 0
    assert 1 <= out[1]["n_tokens"] <= 4
    assert out[2]["n_tokens"] > 1000


def test_core_sizes_and_hashes():
    f = CORE.extract(mk("﻿# Tïtle\nhello world\n"))
    assert f["n_chars"] == len("# Tïtle\nhello world\n")
    assert f["n_bytes"] > f["n_chars"], "multi-byte characters counted in bytes"
    assert f["n_words"] == 4
    assert f["host"] == "acme.example" and f["tld"] == "example"
    assert len(f["content_sha1"]) == 40 and len(f["skeleton_sha1"]) == 40


