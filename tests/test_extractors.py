def test_schema_covers_every_registered_field():
    schema = feature_schema()
    names = set(schema.names)
    for cls in (*row_extractors(), *batch_extractors()):
        assert set(cls.FIELDS) <= names, f"{cls.NAME} fields missing from schema"
    assert len(names) == len(schema), "duplicate column names"


def test_every_extractor_declares_a_track():
    for cls in (*row_extractors(), *batch_extractors()):
        assert cls.NAME and cls.TRACK, cls


