def test_yaml_policy_dialect():
    doc = (
        "spec: llmstxt/1.0\nsite: https://x.example\njurisdiction: US\n\n"
        "agents:\n  allow: [\"*\"]\n  overrides:\n"
        "    GPTBot: {allow: true}\n    ClaudeBot: {allow: true}\n"
        "    CCBot: {allow: true}\n    Bytespider: {allow: false}\n\n"
        "permissions:\n  indexing: allow\n  training:\n    status: allow\n"
    )
    f = POL.extract(mk(doc))
    assert f["policy_dialect"] == "yaml"
    assert f["has_any_policy"]
    assert set(f["named_bots"]) == {"GPTBot", "ClaudeBot", "CCBot", "Bytespider"}
    assert "Bytespider" in f["bots_denied"]
    assert "GPTBot" in f["bots_allowed"]
    assert "jurisdiction" in f["policy_directives"]


def test_robots_dialect_and_training_denial():
    f = POL.extract(mk("User-agent: *\nAllow: /\nDisallow-Training: /\nSitemap: /sitemap.xml\n"))
    assert f["policy_dialect"] == "robots"
    assert f["training_stance"] == "deny"
    assert "disallow_training_header" in f["policy_directives"]


def test_prose_policy_and_stances():
    f = POL.extract(mk("# X\n## Usage policy\nThis content may not be used to train AI models.\n"
                       "Attribution is required.\n"))
    assert f["policy_dialect"] == "prose"
    assert f["has_policy_heading"]
    assert f["training_stance"] == "deny"
    assert "attribution_required" in f["policy_directives"]

    assert POL.extract(mk("training: allow\npermissions:\n"))["training_stance"] == "allow"
    assert POL.extract(mk("Non-commercial use only."))["training_stance"] == "conditional"
    assert POL.extract(mk("# X\n> plain\n- [a](https://x.example/)"))["training_stance"] == "none"


def test_deny_wins_over_allow():
    f = POL.extract(mk("You may use this content to train models.\n"
                       "Actually this content may not be used to train AI models.\n"))
    assert f["training_stance"] == "deny"


def test_bot_named_without_verdict_is_not_counted_as_either():
    f = POL.extract(mk("We see a lot of traffic from GPTBot crawling the site.\n"))
    assert f["named_bots"] == ["GPTBot"]
    assert f["bots_allowed"] == [] and f["bots_denied"] == []


def test_bot_substrings_do_not_false_match():
    f = POL.extract(mk("Our crawler is called NotGPTBotX and it is ours.\n"))
    assert f["named_bots"] == []


