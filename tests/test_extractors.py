# invariants on real corpus records
# --------------------------------------------------------------------------
def test_real_records_produce_complete_features(features):
    schema_names = set(feature_schema().names)
    for f in features:
        assert set(f) == schema_names
        assert f["n_links"] >= f["n_links_with_notes"]
        assert f["n_links"] >= f["n_offsite_links"]
        assert 0.0 <= f["offsite_ratio"] <= 1.0
        assert 0 <= f["injection_severity"] <= 3
        assert 0 <= f["conformance_level"] <= 4
        assert f["n_chars"] >= 0 and f["n_tokens"] >= 0
        assert f["doc_kind"] in {
            "empty", "json", "yaml", "yaml_frontmatter", "html", "robots_txt", "markdown", "plain"
        }
        if f["doc_kind"] not in ("markdown", "yaml_frontmatter"):
            assert f["conformance_level"] == 0
        if f["for_sale"]:
            assert f["for_sale_marketplace"]
        if f["n_chars"] == 0:
            assert f["n_tokens"] == 0 and f["doc_kind"] == "empty"


def test_real_records_cover_every_stratum(features):
    """The fixture is only useful if it still exercises every branch."""
    kinds = {f["doc_kind"] for f in features}
    assert {"markdown", "empty", "json", "robots_txt", "plain"} <= kinds
    gens = {f["generator_id"] for f in features}
    assert {"wix", "yoast", "aioseo", "unknown"} <= gens
    assert {f["conformance_level"] for f in features} >= {0, 1, 2, 3, 4}
    assert max(f["injection_severity"] for f in features) >= 2
    assert any(f["for_sale"] for f in features)
    assert any(f["n_spam_categories"] > 0 for f in features)
    assert any(f["has_any_policy"] for f in features)
    assert any(f["n_named_bots"] > 0 for f in features)
    assert any(f["mentions_mcp"] for f in features)
    assert len({f["lang"] for f in features}) >= 6
    assert any(f["lang_source"] == "glotlid" for f in features)
