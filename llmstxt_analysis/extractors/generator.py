"""Track B — which tool produced the file.

Two layers, in priority order:

1. **Declared** — the generator says so, usually with a version
   ("Generated by Yoast SEO v28.0, this is an llms.txt file ...").
2. **Fingerprint** — a structural marker unique to a platform, chosen to be
   *language-independent* so that localised templates are still detected
   (e.g. Wix's help-centre URL rather than its English prose).
"""
from __future__ import annotations

import re

from ..record import Record
from ..registry import LIST_STR, STR, RowExtractor, register

# (id, family, compiled regex with an optional version group)
_DECLARED: list[tuple[str, str, re.Pattern]] = [
    ("aioseo", "seo_plugin", re.compile(r"All in One SEO(?: Pro)?\s*v?([\d.]+)?", re.I)),
    ("yoast", "seo_plugin", re.compile(r"Yoast SEO\s*v?([\d.]+)?", re.I)),
    ("rankmath", "seo_plugin", re.compile(r"Rank ?Math(?: SEO| PRO)?\s*v?([\d.]+)?", re.I)),
    ("seopress", "seo_plugin", re.compile(r"SEOPress\s*v?([\d.]+)?", re.I)),
    ("squirrly", "seo_plugin", re.compile(r"Squirrly SEO\s*v?([\d.]+)?", re.I)),
    ("slim_seo", "seo_plugin", re.compile(r"Slim SEO\s*v?([\d.]+)?", re.I)),
    ("seo_framework", "seo_plugin", re.compile(r"The SEO Framework\s*v?([\d.]+)?", re.I)),
    ("wpbakery_llms", "seo_plugin", re.compile(r"LLMs\.txt Generator\s*v?([\d.]+)?", re.I)),
]

# Generic "Generated by <X>, this is an llms.txt file" catch-all.
_GENERIC_DECL = re.compile(
    r"(?:Generated|Created|Produced|Powered)\s+by\s+([A-Za-z][A-Za-z0-9 .&+_-]{1,40}?)"
    r"\s*(?:v([\d.]+))?\s*[,.]?\s*(?:this is an?|used by|for)\s+llms",
    re.I,
)

# (id, family, compiled regex, min_hits)
_FINGERPRINTS: list[tuple[str, str, re.Pattern, int]] = [
    # Language-independent: the Wix docs URL is identical in every locale.
    ("wix", "site_builder", re.compile(r"about-the-wix-site-mcp|_api/mcp\b", re.I), 1),
    ("wix", "site_builder", re.compile(r"wixstatic\.com|wixsite\.com|/_functions/", re.I), 1),
    ("mintlify", "docs_platform", re.compile(r"^Source: https?://", re.M), 3),
    ("gitbook", "docs_platform", re.compile(r"gitbook\.(?:io|com)", re.I), 1),
    ("docusaurus", "docs_platform", re.compile(r"docusaurus", re.I), 1),
    ("readme_io", "docs_platform", re.compile(r"readme\.io|readmeio", re.I), 1),
    ("rspress", "docs_platform", re.compile(r"^url: /[a-z0-9/._-]+\.md$", re.M), 2),
    ("shopify", "ecommerce", re.compile(r"cdn\.shopify\.com|myshopify\.com", re.I), 1),
    ("bigcommerce", "ecommerce", re.compile(r"bigcommerce\.com", re.I), 1),
    ("squarespace", "site_builder", re.compile(r"squarespace(?:-cdn)?\.com", re.I), 1),
    ("webflow", "site_builder", re.compile(r"webflow\.(?:io|com)", re.I), 1),
    ("framer", "site_builder", re.compile(r"framer\.(?:app|website|com)", re.I), 1),
    ("duda", "site_builder", re.compile(r"dudaone|duda\.co|multiscreensite", re.I), 1),
    ("weebly", "site_builder", re.compile(r"weebly(?:site)?\.com", re.I), 1),
    ("godaddy_parking", "parking", re.compile(r"forsale\.godaddy\.com|afternic\.com", re.I), 1),
    ("wordpress", "cms", re.compile(r"wp-content|wp-json|/wp-admin", re.I), 1),
]

FAMILY_OF: dict[str, str] = {}
for _id, _fam, *_ in _DECLARED:
    FAMILY_OF[_id] = _fam
for _id, _fam, *_ in _FINGERPRINTS:
    FAMILY_OF.setdefault(_id, _fam)


# Traces that the file was produced by pasting a chat assistant's answer in
# and shipping it: citation markers the UI injects, unfilled placeholders, or
# the fenced code block the answer came wrapped in. Surfaced by the topic
# model, which found whole clusters held together by "oaicite".
_ARTEFACTS: list[tuple[str, str, re.Pattern]] = [
    ("openai_citation", "oaicite",
     re.compile(r"contentReference\[oaicite|:contentReference|\boaicite\b", re.I)),
    ("chatgpt_utm", "utm_source=chatgpt", re.compile(r"utm_source=chatgpt", re.I)),
    ("model_disclaimer", "language model",
     re.compile(r"\bas an ai (?:language )?model\b|\bI(?:'m| am) (?:an|a) (?:AI|large language)", re.I)),
    # The `(?!\()` matters: `[Insert Ltd](https://…)` is an ordinary markdown
    # link to a company called Insert Ltd, not an unfilled template slot.
    ("unfilled_placeholder", "[",
     re.compile(r"\[(?:insert|your|company name|business name|add|tbd|xxx)[^\]\n]{0,40}\](?!\()|"
                r"\bYOUR_(?:COMPANY|DOMAIN|SITE)\b|\blorem ipsum\b", re.I)),
    ("fence_leak", "```", re.compile(r"\A\s*```(?:markdown|md|txt)?\s*\n", re.I)),
]


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.strip().lower()).strip("_")[:40]


@register
class GeneratorExtractor(RowExtractor):
    NAME = "generator"
    TRACK = "B"
    FIELDS = {
        "generator_id": STR,
        "generator_family": STR,
        "generator_version": STR,
        "generator_source": STR,
        "llm_artefacts": LIST_STR,
    }

    def _artefacts(self, rec: Record) -> list[str]:
        text, low = rec.scan, rec.scan_lower
        return [slug for slug, anchor, pat in _ARTEFACTS
                if anchor in low and pat.search(text)]

    def extract(self, rec: Record) -> dict:
        head = rec.head
        artefacts = self._artefacts(rec)

        def out(gid: str, fam: str, version: str, source: str) -> dict:
            return {
                "generator_id": gid,
                "generator_family": fam,
                "generator_version": version,
                "generator_source": source,
                "llm_artefacts": artefacts,
            }

        for gid, fam, pat in _DECLARED:
            m = pat.search(head)
            if m:
                return out(gid, fam, (m.group(1) or "")[:20], "declared")

        m = _GENERIC_DECL.search(head)
        if m:
            gid = _slug(m.group(1))
            if gid:
                return out(gid, FAMILY_OF.get(gid, "other_declared"), (m.group(2) or "")[:20],
                           "declared")

        for gid, fam, pat, min_hits in _FINGERPRINTS:
            hit = pat.search(head) if min_hits == 1 else len(pat.findall(head)) >= min_hits
            if hit:
                return out(gid, fam, "", "fingerprint")

        return out("unknown", "unknown", "", "none")
